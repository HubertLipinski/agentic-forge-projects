/**
 * @fileoverview Template for the generated CLI executable script.
 *
 * This module exports a function that generates the source code for the final
 * CLI file. It acts as a template, dynamically injecting command definitions,
 * import paths, and other metadata into a boilerplate structure. The resulting
 * string is a fully functional Node.js script that uses `commander` to create
 * the command-line interface.
 *
 * @module src/templates/cli-template
 */

/**
 * Generates the source code for the output CLI file.
 *
 * This function constructs a complete, executable Node.js script as a string.
 * It integrates the command definitions derived from JSDoc comments into a
 * `commander` program structure. The template includes necessary imports,
 * sets up the main program, and dynamically adds commands with their respective
 * arguments, options, and action handlers that call the original functions.
 *
 * @param {object} templateData - The data needed to populate the template.
 * @param {string} templateData.programDescription - The top-level description for the CLI program,
 *   often taken from `package.json`.
 * @param {string} templateData.programVersion - The version for the CLI program, from `package.json`.
 * @param {string[]} templateData.importPaths - An array of relative paths to the original source
 *   files containing the functions to be exposed. These are used to generate `import` statements.
 * @param {string[]} templateData.commandSnippets - An array of code snippets, where each snippet
 *   is a complete `.command(...)` chain for `commander`.
 * @returns {string} A string containing the complete source code for the generated CLI.
 */
export function generateCliContent({
  programDescription = 'A CLI generated by jsdoc-to-cli.',
  programVersion = '1.0.0',
  importPaths = [],
  commandSnippets = [],
}) {
  // Generate unique aliases for each imported module to prevent naming conflicts.
  // e.g., './src/math.js' -> 'module0', './src/utils.js' -> 'module1'
  const importStatements = importPaths
    .map((p, i) => `import * as module${i} from '${p}';`)
    .join('\n');

  const allCommands = commandSnippets.join('\n\n');

  // The template string for the generated CLI file.
  // It includes a shebang, ES module imports, and a commander setup.
  return `#!/usr/bin/env node

/**
 * This is an auto-generated file by jsdoc-to-cli.
 * DO NOT EDIT THIS FILE DIRECTLY.
 *
 * Your changes will be overwritten on the next run.
 */

import { Command } from 'commander';
${importStatements}

/**
 * Main function to set up and run the CLI.
 */
async function main() {
  const program = new Command();

  program
    .name('cli') // Note: This will be replaced by the binary name in package.json.
    .description('${programDescription}')
    .version('${programVersion}');

  // --- Command Definitions ---
${allCommands}

  // Handle cases where no command is specified.
  if (!process.argv.slice(2).length) {
    program.outputHelp();
    process.exit(1);
  }

  try {
    await program.parseAsync(process.argv);
  } catch (error) {
    // Gracefully handle errors from command actions.
    // Commander's own error handling (e.g., for missing args) is usually sufficient,
    // but this catches errors thrown from within the imported functions.
    console.error(\`[Error] \${error.message}\`);
    process.exit(1);
  }
}

main();
`;
}