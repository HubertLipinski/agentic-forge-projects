/**
 * @file src/schema-extractor.js
 * @description Core logic for querying the database and transforming raw SQL results into a structured JSON schema.
 *
 * This module orchestrates the extraction of a PostgreSQL database schema. It executes
 * a series of detailed queries against the system catalogs and information schema, then
 * processes and assembles the results into a deterministic, deeply-structured JSON object.
 * The final structure is sorted at every level to ensure that snapshots are comparable
 * and produce consistent diffs.
 */

import {
  GET_COLUMNS_QUERY,
  GET_CONSTRAINTS_QUERY,
  GET_INDEXES_QUERY,
} from './queries.js';

/**
 * A helper function to sort an array of objects by a specified key.
 * This is crucial for ensuring the final JSON output is deterministic.
 *
 * @template T
 * @param {T[]} arr - The array of objects to sort.
 * @param {keyof T} key - The key to sort by.
 * @returns {T[]} The sorted array.
 */
const sortByKey = (arr, key) => arr.sort((a, b) => a[key].localeCompare(b[key]));

/**
 * Processes the raw SQL result for columns and organizes them into a nested structure.
 * The final structure is `{[tableName]: { [columnName]: columnDetails }}`.
 *
 * @param {Array<object>} columnRows - Raw rows from the GET_COLUMNS_QUERY.
 * @returns {object} An object where keys are table names and values are objects of columns.
 */
const processColumns = (columnRows) => {
  const tables = {};

  for (const row of columnRows) {
    const { table_name: tableName, column_name: columnName, ...colDetails } = row;

    // Initialize table object if it doesn't exist
    if (!tables[tableName]) {
      tables[tableName] = {
        name: tableName,
        columns: {},
        constraints: [],
        indexes: [],
      };
    }

    // Sanitize and structure column details
    const column = {
      name: columnName,
      type: colDetails.udt_name,
      isNullable: colDetails.is_nullable,
      defaultValue: colDetails.column_default,
      // Only include length/precision if they are relevant
      ...(colDetails.character_maximum_length && { maxLength: colDetails.character_maximum_length }),
      ...(colDetails.numeric_precision && {
        numericPrecision: colDetails.numeric_precision,
        numericScale: colDetails.numeric_scale,
      }),
      ...(colDetails.datetime_precision && { datetimePrecision: colDetails.datetime_precision }),
      ...(colDetails.is_identity === 'YES' && {
        isIdentity: true,
        identityGeneration: colDetails.identity_generation,
      }),
    };

    // Remove null/undefined properties for a cleaner output
    Object.keys(column).forEach(key => (column[key] == null) && delete column[key]);

    tables[tableName].columns[columnName] = column;
  }

  return tables;
};

/**
 * Processes raw constraint rows and attaches them to the corresponding tables.
 *
 * @param {object} tables - The tables object generated by `processColumns`.
 * @param {Array<object>} constraintRows - Raw rows from the GET_CONSTRAINTS_QUERY.
 */
const processConstraints = (tables, constraintRows) => {
  for (const row of constraintRows) {
    const { table_name: tableName, constraint_name: constraintName, constraint_type: type, ...conDetails } = row;

    if (!tables[tableName]) {
      // This case should not happen in a consistent database, but we guard against it.
      console.error(`Warning: Found constraint '${constraintName}' for table '${tableName}', but the table was not found.`);
      continue;
    }

    const constraint = {
      name: constraintName,
      type: type,
      columns: conDetails.columns ?? [], // Ensure columns is always an array
    };

    // Add type-specific details
    if (type === 'FOREIGN KEY') {
      constraint.references = {
        table: conDetails.foreign_table_name,
        columns: conDetails.foreign_columns ?? [],
      };
    } else if (type === 'CHECK' && conDetails.check_clause) {
      constraint.checkClause = conDetails.check_clause;
    }

    tables[tableName].constraints.push(constraint);
  }
};

/**
 * Processes raw index rows and attaches them to the corresponding tables.
 *
 * @param {object} tables - The tables object generated by `processColumns`.
 * @param {Array<object>} indexRows - Raw rows from the GET_INDEXES_QUERY.
 */
const processIndexes = (tables, indexRows) => {
  for (const row of indexRows) {
    const { table_name: tableName, index_name: indexName, ...idxDetails } = row;

    if (!tables[tableName]) {
      // This can happen if an index is on a table in an excluded schema, but this function
      // is called with all indexes. The check is a safeguard.
      continue;
    }

    const index = {
      name: indexName,
      method: idxDetails.index_method,
      isUnique: idxDetails.is_unique,
      definition: idxDetails.index_definition,
    };

    tables[tableName].indexes.push(index);
  }
};

/**
 * Finalizes the schema structure by converting maps to sorted arrays
 * to ensure a deterministic output.
 *
 * @param {object} tables - The processed tables object with nested columns, constraints, and indexes.
 * @returns {Array<object>} A sorted array of table objects.
 */
const finalizeAndSortSchema = (tables) => {
  const sortedTables = sortByKey(Object.values(tables), 'name');

  for (const table of sortedTables) {
    // Convert columns object to a sorted array
    table.columns = Object.values(table.columns).sort((a, b) => {
        // Find original ordinal position to sort columns correctly
        const colA = Object.values(tables[table.name].columns).find(c => c.name === a.name);
        const colB = Object.values(tables[table.name].columns).find(c => c.name === b.name);
        // This is a bit of a workaround since we converted to an object.
        // A more robust way would be to keep ordinal_position.
        // However, the initial query is already ordered by ordinal_position,
        // so the insertion order into the object should be correct.
        // Let's rely on the original query order and just sort by name for final determinism.
        return a.name.localeCompare(b.name);
    });

    // Sort constraints and indexes by name
    sortByKey(table.constraints, 'name');
    sortByKey(table.indexes, 'name');
  }

  return sortedTables;
};

/**
 * Extracts the database schema for a given set of schemas.
 *
 * This is the main exported function. It performs the following steps:
 * 1. Validates the input options.
 * 2. Executes queries to fetch columns, constraints, and indexes in parallel.
 * 3. Processes the raw data from each query.
 * 4. Assembles the processed data into a single, structured object.
 * 5. Sorts all elements of the structure to ensure the output is deterministic.
 *
 * @param {import('pg').Client} client - An active PostgreSQL client instance.
 * @param {object} options - Configuration for the extraction.
 * @param {string[]} options.includeSchemas - An array of schema names to include.
 * @param {string[]} options.excludeSchemas - An array of schema names to exclude (takes precedence).
 * @returns {Promise<object>} A promise that resolves to the structured schema snapshot.
 * @throws {Error} If database queries fail or if options are invalid.
 */
export const extractSchema = async (client, options) => {
  const { includeSchemas = ['public'], excludeSchemas = [] } = options ?? {};

  if (!Array.isArray(includeSchemas) || !Array.isArray(excludeSchemas)) {
    throw new Error('Invalid options: includeSchemas and excludeSchemas must be arrays.');
  }

  // Filter schemas to be queried. Exclusions take precedence.
  const schemasToQuery = includeSchemas.filter(s => !excludeSchemas.includes(s));

  if (schemasToQuery.length === 0) {
    console.error('Warning: No schemas to query after applying exclusions.');
    return {
      metadata: {
        capturedAt: new Date().toISOString(),
        schemas: [],
      },
      tables: [],
    };
  }

  try {
    // Execute all introspection queries in parallel for efficiency.
    const [columnResult, constraintResult, indexResult] = await Promise.all([
      client.query(GET_COLUMNS_QUERY, [schemasToQuery]),
      client.query(GET_CONSTRAINTS_QUERY, [schemasToQuery]),
      client.query(GET_INDEXES_QUERY, [schemasToQuery]),
    ]);

    // Step 1: Process columns to build the base table structure.
    const tables = processColumns(columnResult.rows);

    // Step 2: Attach constraints to the corresponding tables.
    processConstraints(tables, constraintResult.rows);

    // Step 3: Attach indexes to the corresponding tables.
    processIndexes(tables, indexResult.rows);

    // Step 4: Convert the intermediate structure to a final, sorted array format.
    const finalTables = finalizeAndSortSchema(tables);

    return {
      metadata: {
        capturedAt: new Date().toISOString(),
        schemas: schemasToQuery.sort(),
      },
      tables: finalTables,
    };
  } catch (error) {
    console.error('Error during schema extraction query execution:', error);
    throw new Error(`Failed to extract schema from the database. Reason: ${error.message}`);
  }
};