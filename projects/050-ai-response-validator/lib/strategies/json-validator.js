/**
 * @file lib/strategies/json-validator.js
 * @description Implements the validation strategy for JSON data using Ajv.
 * @module lib/strategies/json-validator
 */

import Ajv from 'ajv';
import { ValidationError } from '../errors.js';
import { VALIDATION_STRATEGIES } from '../constants.js';

/**
 * A validation strategy for ensuring a string is valid JSON and optionally
 * conforms to a given JSON schema.
 *
 * This class leverages the Ajv library for robust and performant schema validation.
 * It first checks if the input string can be parsed as JSON, then validates
 * the resulting object against the provided schema.
 */
export class JsonValidator {
  /**
   * The unique identifier for this validation strategy.
   * @type {string}
   */
  static name = VALIDATION_STRATEGIES.JSON;

  /**
   * The Ajv instance used for schema validation. It is initialized lazily
   * on the first validation call that requires a schema.
   * @type {Ajv | null}
   * @private
   */
  #ajv = null;

  /**
   * The compiled validation function generated by Ajv. This is cached for
   * performance, so the schema doesn't need to be re-compiled on every call.
   * @type {import('ajv').ValidateFunction | null}
   * @private
   */
  #validateFunction = null;

  /**
   * The JSON schema to validate against.
   * @type {object | null}
   * @private
   */
  #schema;

  /**
   * Creates an instance of JsonValidator.
   * @param {object} [options={}] - Configuration options for the validator.
   * @param {object} [options.schema] - A valid JSON schema object to validate the response against.
   * If not provided, the validator will only check for well-formed JSON.
   */
  constructor(options = {}) {
    this.#schema = options.schema ?? null;
  }

  /**
   * Initializes the Ajv instance and compiles the schema if it hasn't been done yet.
   * This is called just-in-time to avoid unnecessary setup if no schema is provided.
   * @private
   */
  #initializeAjv() {
    if (!this.#ajv) {
      this.#ajv = new Ajv();
    }
    if (!this.#validateFunction && this.#schema) {
      try {
        this.#validateFunction = this.#ajv.compile(this.#schema);
      } catch (error) {
        // This catches schema compilation errors from Ajv.
        throw new ValidationError(
          `Invalid JSON schema provided: ${error.message}`,
          { cause: error },
        );
      }
    }
  }

  /**
   * Validates the given LLM response string.
   *
   * The method performs two main checks:
   * 1.  It verifies that the input string is well-formed JSON.
   * 2.  If a schema was provided to the constructor, it validates the parsed
   *     JSON object against that schema.
   *
   * @param {string} response - The string response from the LLM, expected to be JSON.
   * @returns {Promise<{ isValid: boolean, data: object | null, error: string | null }>}
   * An object indicating the validation result.
   * - `isValid`: `true` if the response is valid, `false` otherwise.
   * - `data`: The parsed JSON object if validation is successful, otherwise `null`.
   * - `error`: A detailed error message if validation fails, otherwise `null`.
   */
  async validate(response) {
    let parsedJson;

    try {
      parsedJson = JSON.parse(response);
    } catch (error) {
      return {
        isValid: false,
        data: null,
        error: `Invalid JSON: The response could not be parsed. Error: ${error.message}`,
      };
    }

    // If no schema is provided, we only care about well-formedness.
    if (!this.#schema) {
      return {
        isValid: true,
        data: parsedJson,
        error: null,
      };
    }

    // Lazily initialize Ajv and compile the schema on first use.
    this.#initializeAjv();

    const isValid = this.#validateFunction(parsedJson);

    if (isValid) {
      return {
        isValid: true,
        data: parsedJson,
        error: null,
      };
    }

    const errorDetails = this.#ajv.errorsText(this.#validateFunction.errors, {
      separator: '; ',
      dataVar: 'response',
    });

    return {
      isValid: false,
      data: parsedJson, // Return the parsed (but invalid) data for context
      error: `JSON schema validation failed: ${errorDetails}`,
    };
  }
}