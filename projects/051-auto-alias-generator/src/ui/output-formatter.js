import chalk from 'chalk';
import { APP_NAME } from '../utils/constants.js';

/**
 * @fileoverview Formats the final list of selected aliases for display in the terminal.
 * This module is responsible for generating the user-facing output, including
 * instructions and the formatted alias definitions ready for copy-pasting into
 * a shell configuration file (e.g., .bashrc, .zshrc).
 */

/**
 * Generates a formatted string for a single alias definition.
 * The format is `alias <alias_name>='<original_command>'`.
 *
 * @param {object} aliasData - The alias data object.
 * @param {string} aliasData.alias - The short alias name (e.g., 'gs').
 * @param {string} aliasData.command - The original, full command (e.g., 'git status').
 * @returns {string} A shell-compatible alias definition string.
 */
function formatAliasDefinition({ alias, command }) {
  // Escape single quotes in the command to prevent breaking the alias definition.
  // ' -> '\''
  const escapedCommand = command.replace(/'/g, "'\\''");
  return `alias ${alias}='${escapedCommand}'`;
}

/**
 * Creates a visually distinct header for the output section.
 *
 * @param {string} title - The text to display in the header.
 * @returns {string} The formatted header string.
 */
function createHeader(title) {
  const separator = '─'.repeat(title.length + 4);
  return chalk.bold.yellow(`\n┌${separator}┐\n│  ${title}  │\n└${separator}┘\n`);
}

/**
 * Generates the final output string to be displayed to the user.
 * This includes a header, instructions for use, and the list of formatted
 * alias definitions.
 *
 * @param {object} options - The formatting options.
 * @param {Array<{command: string, alias: string}>} options.selectedAliases - An array of aliases chosen by the user.
 * @param {string} options.shellType - The detected shell type ('zsh', 'bash', 'fish', etc.).
 * @returns {string} The complete, formatted output string for the console.
 */
export function formatOutput({ selectedAliases, shellType }) {
  if (!Array.isArray(selectedAliases)) {
    throw new Error('Input "selectedAliases" must be an array.');
  }

  if (selectedAliases.length === 0) {
    return chalk.green('No aliases were selected. Nothing to do. Exiting.');
  }

  // Determine the appropriate config file name based on the detected shell.
  // Fallback to a generic name if the shell is unknown.
  const configFile = {
    zsh: '.zshrc',
    bash: '.bashrc',
    fish: 'config.fish',
  }[shellType] ?? 'your shell configuration file';

  const header = createHeader('Your New Aliases');

  const instructions = chalk.dim(
    `Copy the lines below and paste them into your ~/${chalk.bold(configFile)} file to apply.`
  );

  // For Fish shell, the alias syntax is different: `alias gs 'git status'`.
  // The standard format `alias gs='git status'` also works in recent Fish versions,
  // but the space-separated format is more idiomatic. We will stick to the
  // POSIX-compatible format for simplicity and broader compatibility, as it
  // works in Bash, Zsh, and Fish. If specific Fish syntax is required, this is where
  // the logic would be adapted.

  const aliasDefinitions = selectedAliases
    .map(aliasData => {
      const definition = formatAliasDefinition(aliasData);
      const comment = chalk.dim(`# ${aliasData.command}`);
      // Align comments for better readability. Find the longest definition.
      return { definition, comment };
    })
    .map(({ definition, comment }) => {
        // A simple fixed padding works well for most cases without over-complicating.
        return `${definition.padEnd(40)} ${comment}`;
    });

  const generatedBy = chalk.italic.gray(
    `\n# Generated by ${APP_NAME} on ${new Date().toISOString()}`
  );

  // Assemble all parts into the final output string.
  return [
    header,
    instructions,
    '', // Adds a blank line for spacing
    generatedBy,
    ...aliasDefinitions,
    '\n', // Final newline for clean exit
  ].join('\n');
}

/**
 * Prints the formatted output directly to the console.
 * This is a convenience wrapper around `formatOutput` and `console.log`.
 *
 * @param {object} options - The formatting options, passed directly to `formatOutput`.
 */
export function printFormattedOutput(options) {
  try {
    const output = formatOutput(options);
    console.log(output);
  } catch (error) {
    // This catch block handles potential errors from the formatting logic itself.
    console.error(chalk.red('An unexpected error occurred while formatting the output:'), error.message);
  }
}