/**
 * @file src/parser/dependency-extractor.js
 * @description Extracts dependency specifiers from a JavaScript AST.
 *
 * This module uses `acorn-walk` to traverse an Abstract Syntax Tree (AST)
 * and identify all forms of module dependencies, including:
 * - ES Module `import` statements (`import x from 'y'`)
 * - ES Module `export from` statements (`export * from 'z'`)
 * - ES Module dynamic `import()` expressions
 * - CommonJS `require()` calls
 * - CommonJS dynamic `require()` calls with string literals
 */

import { simple as simpleWalk } from 'acorn-walk';
import logger from '../utils/logger.js';

/**
 * @typedef {import('acorn').Node} AcornNode
 */

/**
 * @typedef {object} Dependency
 * @property {string} specifier - The raw module specifier (e.g., './utils', 'react').
 * @property {number} start - The starting character index of the specifier in the source.
 * @property {number} end - The ending character index of the specifier in the source.
 * @property {boolean} isDynamic - True if the dependency is from a dynamic import() or require().
 */

/**
 * Extracts all dependency specifiers from a given Abstract Syntax Tree (AST).
 *
 * It traverses the AST using `acorn-walk` and collects specifiers from various
 * node types that represent module dependencies in both ES Modules and CommonJS.
 *
 * Supported patterns:
 * - `import ... from 'module-specifier'`
 * - `export ... from 'module-specifier'`
 * - `import('module-specifier')`
 * - `require('module-specifier')`
 *
 * @param {AcornNode} ast - The AST to analyze, generated by Acorn.
 * @param {string} filePath - The path of the file corresponding to the AST, used for logging.
 * @returns {Dependency[]} An array of found dependency objects. Returns an empty array if no dependencies are found or if the AST is invalid.
 */
export function extractDependencies(ast, filePath) {
  if (!ast || typeof ast.type !== 'string') {
    logger.warn(`[Extractor] Invalid or null AST provided for file: ${filePath}. Skipping extraction.`);
    return [];
  }

  /** @type {Dependency[]} */
  const dependencies = [];
  const foundSpecifiers = new Set();

  try {
    simpleWalk(ast, {
      // Handles:
      // - import defaultExport from 'module-specifier';
      // - import * as name from 'module-specifier';
      // - import { export1, export2 } from 'module-specifier';
      ImportDeclaration(node) {
        if (node.source?.type === 'Literal' && typeof node.source.value === 'string') {
          const specifier = node.source.value;
          // Use a Set to prevent duplicates from different AST nodes pointing to the same source literal.
          if (!foundSpecifiers.has(specifier)) {
            dependencies.push({
              specifier,
              start: node.source.start,
              end: node.source.end,
              isDynamic: false,
            });
            foundSpecifiers.add(specifier);
          }
        }
      },

      // Handles:
      // - export * from 'module-specifier';
      // - export { name1, name2 } from 'module-specifier';
      ExportAllDeclaration(node) {
        if (node.source?.type === 'Literal' && typeof node.source.value === 'string') {
          dependencies.push({
            specifier: node.source.value,
            start: node.source.start,
            end: node.source.end,
            isDynamic: false,
          });
        }
      },
      ExportNamedDeclaration(node) {
        if (node.source?.type === 'Literal' && typeof node.source.value === 'string') {
          dependencies.push({
            specifier: node.source.value,
            start: node.source.start,
            end: node.source.end,
            isDynamic: false,
          });
        }
      },

      // Handles:
      // - require('module-specifier')
      // - import('module-specifier')
      CallExpression(node) {
        const isRequire = node.callee.type === 'Identifier' && node.callee.name === 'require';
        const isDynamicImport = node.callee.type === 'Import'; // `import()` is a special `Import` node in the AST

        if (isRequire || isDynamicImport) {
          if (node.arguments.length > 0 && node.arguments[0].type === 'Literal' && typeof node.arguments[0].value === 'string') {
            const specifier = node.arguments[0].value;
            // Avoid adding empty require('') calls
            if (specifier) {
              dependencies.push({
                specifier,
                start: node.arguments[0].start,
                end: node.arguments[0].end,
                isDynamic: true,
              });
            }
          } else {
            // Handle dynamic requires with expressions, e.g., require(`./locales/${lang}.json`)
            // We log this as we cannot statically resolve it, which is important for the user to know.
            logger.debug(`[Extractor] Found non-literal argument for ${isRequire ? 'require' : 'import'} in ${filePath}. Cannot statically resolve.`);
          }
        }
      },
    });
  } catch (error) {
    logger.error(`[Extractor] Error walking AST for file: ${filePath}`, error);
    // Return whatever was found before the error, or an empty array.
    return dependencies;
  }

  logger.debug(`[Extractor] Found ${dependencies.length} dependencies in ${filePath}`);
  return dependencies;
}